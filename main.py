"""
Run every experiment, save figures + CSV + an auto-generated markdown report to ./results.

    python main.py            # full run (~2-4 min)
    python main.py --quick    # fewer trials, for a fast check (~20 s)
"""
import argparse
import csv
import json
import os
import time

from src import experiments as E


def write_csv(rows, path):
    with open(path, "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)


def table(summary, ns_show, metrics=("accuracy", "log_loss", "ece")):
    rows = [r for r in summary["rows"] if r["n_per_class"] in ns_show and r["model"] != "BayesPlugIn"]
    head = "| n / class | model | " + " | ".join(metrics) + " |\n|---|---|" + "---|" * len(metrics) + "\n"
    body = ""
    for r in rows:
        vals = []
        for m in metrics:
            v = r[m + "_median"] if m == "log_loss" else r[m]
            vals.append(f"{v:.3f}")
        body += f"| {r['n_per_class']} | {'MLE' if r['model'] == 'MLE' else 'Bayes'} | " + " | ".join(vals) + " |\n"
    opt = summary["optimal"]
    body += f"| ∞ | Bayes-optimal | {opt['accuracy']:.3f} | {opt['log_loss']:.3f} | – |\n"
    return head + body


def prior_table(ps):
    ns = ps["n"]
    show = [i for i, n in enumerate(ns) if n in (3, 10, 50, 300)]
    head = "| prior | model | " + " | ".join(f"n={ns[i]}" for i in show) + " |\n|---|---|" + "---|" * len(show) + "\n"
    body = ""
    for setting, d in ps.items():
        if setting == "n":
            continue
        for model, accs in d.items():
            body += f"| {setting} | {model} | " + " | ".join(f"{accs[i]:.3f}" for i in show) + " |\n"
    return head + body


def build_report(R, out):
    pe = R["parameter_estimation"]
    lc, hd, cal = R["learning_2d"], R["learning_highdim"], R["calibration"]
    i5 = pe["n"].index(5)
    txt = f"""# Results: MLE vs Bayesian parameter estimation

*Auto-generated by `main.py`. All data are simulated, so the true parameters are known.*

## 1. Parameter estimation (`01_parameter_estimation_mse.png`, `02_posterior_evolution.png`)

| n = 5 | MSE of MLE | MSE of Bayesian posterior mean |
|---|---|---|
| Bernoulli p | {pe['bernoulli']['mle'][i5]:.4f} | {pe['bernoulli']['bayes'][i5]:.4f} |
| Gaussian mean | {pe['gauss_mean']['mle'][i5]:.4f} | {pe['gauss_mean']['bayes'][i5]:.4f} |

95 % interval coverage for the Gaussian mean at n = 5: MLE (frequentist CI) {pe['gauss_mean']['coverage_mle'][i5]:.3f},
Bayesian credible interval {pe['gauss_mean']['coverage_bayes'][i5]:.3f}.
At n = 200 the two estimators' MSEs are {pe['gauss_mean']['mle'][-1]:.4f} vs {pe['gauss_mean']['bayes'][-1]:.4f}: the prior has washed out.

## 2. Classifier, 2-D problem (`03_learning_curves_2d.png`)

{table(lc, [3, 5, 12, 35, 100, 500])}
(log-loss is the median over trials; MLE's mean log-loss is dominated by rare huge values at tiny n.)

## 3. Classifier, 10-D problem (`04_learning_curves_highdim.png`)

{table(hd, [11, 15, 30, 80, 300, 600])}

## 4. Calibration at n = 5 per class (`06_calibration_small_n.png`)

| | accuracy | mean confidence | share of predictions with confidence > 0.99 |
|---|---|---|---|
| MLE | {cal['MLE']['accuracy']:.3f} | {cal['MLE']['mean_confidence']:.3f} | {cal['MLE']['frac_conf_above_0.99']:.3f} |
| Bayes | {cal['Bayes']['accuracy']:.3f} | {cal['Bayes']['mean_confidence']:.3f} | {cal['Bayes']['frac_conf_above_0.99']:.3f} |

A calibrated model's mean confidence matches its accuracy. If confidence is well above accuracy, the model is **over-confident**.

## 5. Prior sensitivity (`07_prior_sensitivity.png`)

Test accuracy, varying prior strength κ₀ (≈ the number of pseudo-observations behind the prior mean):

{prior_table(R['prior_sensitivity'])}

## 6. Decision boundaries

See `05_decision_boundaries.png`.
"""
    with open(os.path.join(out, "REPORT.md"), "w") as f:
        f.write(txt)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true", help="fewer Monte-Carlo trials")
    ap.add_argument("--out", default="results")
    args = ap.parse_args()
    os.makedirs(args.out, exist_ok=True)
    q = args.quick
    t0 = time.time()
    R = {}
    steps = [
        ("parameter_estimation", lambda: E.exp_parameter_estimation(args.out, n_trials=400 if q else 2000)),
        ("learning_2d", lambda: E.exp_learning_curves_2d(args.out, n_trials=30 if q else 200, n_test=5000 if q else 20000)),
        ("learning_highdim", lambda: E.exp_learning_curves_highdim(args.out, n_trials=15 if q else 100, n_test=5000 if q else 20000)),
        ("decision_boundaries", lambda: E.exp_decision_boundaries(args.out)),
        ("calibration", lambda: E.exp_calibration(args.out, n_trials=60 if q else 300)),
        ("prior_sensitivity", lambda: E.exp_prior_sensitivity(args.out, n_trials=25 if q else 150)),
    ]
    for name, fn in steps:
        t = time.time()
        R[name] = fn()
        print(f"[done] {name:22s} {time.time() - t:6.1f}s")

    write_csv(R["learning_2d"]["rows"], os.path.join(args.out, "learning_curves_2d.csv"))
    write_csv(R["learning_highdim"]["rows"], os.path.join(args.out, "learning_curves_highdim.csv"))
    with open(os.path.join(args.out, "all_results.json"), "w") as f:
        json.dump({k: v for k, v in R.items() if v is not None}, f, indent=1, default=float)
    build_report(R, args.out)
    print(f"\nAll done in {time.time() - t0:.1f}s. See {args.out}/REPORT.md and the PNG figures.")


if __name__ == "__main__":
    main()
